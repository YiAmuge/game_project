// Pack the latest approved separate body/weapon without repainting their art.
import {readFile,writeFile,copyFile,mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {decodePNG,encodePNG} from './png.mjs';
const root=resolve(import.meta.dirname,'..'),dir=resolve(root,'src/assets');
await mkdir(resolve(dir,'source'),{recursive:true});
for(const [arg,file]of [[2,'ahab-gasharpoon-body.png'],[3,'ahab-gasharpoon-arm.png']])if(process.argv[arg])await copyFile(resolve(process.argv[arg]),resolve(dir,'source',file));
const sources={},inputs={};
for(const key of ['body','arm']){const file=`source/ahab-gasharpoon-${key}.png`,bytes=await readFile(resolve(dir,file));inputs[key]=decodePNG(bytes);sources[key]={file,sha256:createHash('sha256').update(bytes).digest('hex')};}
const sprites=[];
function pack(key,input,{angle=0,anchor,region,withoutBlade=false,height=480}={}){
 const ca=Math.cos(angle),sa=Math.sin(angle);let l=Infinity,t=Infinity,r=-Infinity,b=-Infinity;
 const valid=(x,y)=>input.data[(y*input.width+x)*4+3]>=100&&(!region||x>=region[0]&&y>=region[1]&&x<region[0]+region[2]&&y<region[1]+region[3])&&(!withoutBlade||y<1180);
 for(let y=0;y<input.height;y++)for(let x=0;x<input.width;x++)if(valid(x,y)){const u=x*ca-y*sa,v=x*sa+y*ca;l=Math.min(l,u);r=Math.max(r,u);t=Math.min(t,v);b=Math.max(b,v);}
 l=Math.floor(l);t=Math.floor(t);r=Math.ceil(r);b=Math.ceil(b);
 // Both arm versions keep identical geometry so ejecting the blade cannot
 // make the arm jump, change scale, or detach from its shoulder anchor.
 if(withoutBlade){const full=sprites.find(s=>s.key==='ahabGasArm');({l,t,r,b}=full.bounds);}
 const scale=height/(b-t+1),w=Math.ceil((r-l+1)*scale),h=height,data=new Uint8Array(w*h*4);
 for(let y=0;y<h;y++)for(let x=0;x<w;x++){
  const u=l+(x+.5)/scale,v=t+(y+.5)/scale,sx=Math.round(u*ca+v*sa),sy=Math.round(-u*sa+v*ca);
  if(sx<0||sy<0||sx>=input.width||sy>=input.height||!valid(sx,sy))continue;
  const at=(sy*input.width+sx)*4;data.set(input.data.subarray(at,at+4),(y*w+x)*4);
 }
 const frame={sheet:23,rotation:0,source:sources[key==='ahabGasBody'?'body':'arm'].file};
 if(anchor){const u=anchor[0]*ca-anchor[1]*sa,v=anchor[0]*sa+anchor[1]*ca;frame.grip=[(u-l)/(r-l+1),(v-t)/(b-t+1)];}
 if(key==='ahabGasBody')Object.assign(frame,{heightScale:1,heightBasis:'crown',referenceHeight:height,foot:[.55,1],face:[w*.52,h*.13,w*.31,h*.29]});
 sprites.push({key,w,h,data,frame,bounds:{l,t,r,b}});
}
pack('ahabGasBody',inputs.body);
const angle=-Math.atan2(1515-775,132-405),armOptions={angle,anchor:[405,775],height:360};
pack('ahabGasArm',inputs.arm,armOptions);
pack('ahabGasArmEmpty',inputs.arm,{...armOptions,withoutBlade:true});
pack('ahabGasBlade',inputs.arm,{angle,region:[110,1178,280,360],height:180});
const pad=8,width=Math.max(...sprites.map(s=>s.w))+pad*2,height=sprites.reduce((n,s)=>n+s.h+pad,pad),data=new Uint8Array(width*height*4),frames={};let top=pad;
for(const s of sprites){for(let y=0;y<s.h;y++)data.set(s.data.subarray(y*s.w*4,(y+1)*s.w*4),((top+y)*width+pad)*4);frames[s.key]={x:pad,y:top,w:s.w,h:s.h,...s.frame};top+=s.h+pad;}
await writeFile(resolve(dir,'ahab-gasharpoon.png'),encodePNG({width,height,data}));
await writeFile(resolve(dir,'ahab-gasharpoon.json'),JSON.stringify({sources,frames},null,2)+'\n');
await writeFile(resolve(root,'src/ahab-ego-sprites.js'),'// Generated by tools/import-ahab-ego.mjs.\nexport const AHAB_EGO_FRAMES='+JSON.stringify(frames,null,2)+';\n');
console.log(`Packed ${sprites.length} GasHarpoon frames into ${width}x${height}.`);
