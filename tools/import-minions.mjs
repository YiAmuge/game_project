// Extract approved source pixels, remove detached alpha residue, normalize body height, and pack.
import{readFile,writeFile,mkdir}from'node:fs/promises';
import{createHash}from'node:crypto';
import{decodePNG,encodePNG}from'./png.mjs';
const sources=[
 {family:'uniform',color:'blue',file:'exec-46139424-878d-4622-9418-16ba7db35b82.png',axes:[210,700,210,700,215,700],feet:[null,null,null,null,1518,1517]},
 {family:'uniform',color:'red',file:'exec-9e9677a3-d6c9-4e56-9a19-8d7101a6bc88.png',axes:[235,680,230,710,215,700],feet:[null,null,null,null,1507,1511]},
 {family:'suit',color:'blue',file:'exec-d20f26d7-7091-47a3-9031-ba69f56fd0f1.png',axes:[382,930,382,930,380,925]},
 {family:'suit',color:'red',file:'exec-c7806078-5163-42ea-a7d7-8c6ffcc77d03.png',axes:[382,930,382,930,380,925]},
];
const width=3072,height=1792,data=new Uint8Array(width*height*4),frames={},provenance=[];let index=0;
await mkdir('src/assets/minions',{recursive:true});
for(const src of sources){
 const bytes=await readFile('/workspace/generated_images/'+src.file),im=decodePNG(bytes),{width:w,height:h}=im,seen=new Uint8Array(w*h),queue=new Int32Array(w*h),components=[];
 for(let p=0;p<w*h;p++){
  if(seen[p]||im.data[p*4+3]<192)continue;
  let end=1,head=0,l=w,t=h,r=0,b=0;seen[p]=1;queue[0]=p;
  while(head<end){const at=queue[head++],x=at%w,y=(at/w)|0;l=Math.min(l,x);t=Math.min(t,y);r=Math.max(r,x+1);b=Math.max(b,y+1);
   for(let dy=-1;dy<=1;dy++)for(let dx=-1;dx<=1;dx++){const xx=x+dx,yy=y+dy,n=yy*w+xx;if(xx<0||yy<0||xx>=w||yy>=h||seen[n]||im.data[n*4+3]<192)continue;seen[n]=1;queue[end++]=n;}
  }
  if(end>2000)components.push({l,t,r,b,pixels:queue.slice(0,end)});
 }
 components.sort((a,b)=>Math.floor((a.t+a.b)/2/(h/3))-Math.floor((b.t+b.b)/2/(h/3))||a.l-b.l);
 if(components.length!==6)throw Error(src.file+': expected six components, got '+components.length);
 provenance.push({family:src.family,color:src.color,file:src.file,sha256:createHash('sha256').update(bytes).digest('hex')});
 for(let n=0;n<6;n++){
  const c=components[n],role=['melee','ranged','siege'][Math.floor(n/2)],pose=n%2?'attack':'idle',key=[src.family,src.color,role,pose].join('_'),mask=new Uint8Array(w*h);
  for(const p of c.pixels)mask[p]=1;
  const footY=src.feet?.[n]??c.b,scale=400/(footY-c.t),padding=8,sw=Math.round((c.r-c.l)*scale)+16,sh=Math.round((c.b-c.t)*scale)+16,sprite=new Uint8Array(sw*sh*4);
  for(let y=0;y<sh-16;y++)for(let x=0;x<sw-16;x++){
   const sx=c.l+Math.min(c.r-c.l-1,Math.floor(x/scale)),sy=c.t+Math.min(c.b-c.t-1,Math.floor(y/scale)),from=sy*w+sx;if(!mask[from])continue;
   const at=((y+padding)*sw+x+padding)*4;sprite.set(im.data.subarray(from*4,from*4+3),at);sprite[at+3]=255;
  }
  const ax=index%6*512+8,ay=Math.floor(index/6)*448+8;if(sw>496||sh>432)throw Error('Cell overflow '+key);
  for(let y=0;y<sh;y++)data.set(sprite.subarray(y*sw*4,(y+1)*sw*4),((ay+y)*width+ax)*4);
  frames[key]={x:ax,y:ay,w:sw,h:sh,sheet:12,family:src.family,color:src.color,role,pose,source:src.file,sourceRect:[c.l,c.t,c.r-c.l,c.b-c.t],referenceHeight:400,crownOffset:8,heightScale:sh/400,foot:[((src.axes[n]-c.l)*scale+8)/sw,408/sh],facesLeft:src.family==='suit'};
  await writeFile('src/assets/minions/'+key+'.png',encodePNG({width:sw,height:sh,data:sprite}));index++;
 }
}
await writeFile('src/assets/minions-v52.png',encodePNG({width,height,data}));
await writeFile('src/assets/minions-v52.json',JSON.stringify({version:1,provenance,extraction:{alphaThreshold:192,component:'largest connected body/weapon silhouette',referenceHeight:400},frames},null,2)+'\n');
await writeFile('src/minion-sprites.js','// Generated by tools/import-minions.mjs; approved sources are in assets/minions-v52.json.\nexport const MINION_FRAMES='+JSON.stringify(frames,null,2)+';\n');
console.log('Imported '+index+' latest red/blue minion poses from four approved sheets.');
