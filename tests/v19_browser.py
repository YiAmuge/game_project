"""Combat changes through real training controls, mouse/key casts and rendered effects."""
import json, os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
art=Path(__file__).resolve().parents[1]/'artifacts';art.mkdir(exist_ok=True)
with sync_playwright() as pw:
    b=pw.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH','/usr/bin/chromium'),headless=True,args=['--no-sandbox'])
    page=b.new_page(viewport={'width':1440,'height':900});errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(os.environ.get('MOBA_TEST_URL','http://127.0.0.1:5180')+'/?debug=1',wait_until='networkidle')
    expect(page.locator('.build-tag')).to_contain_text('0.20.0')
    page.click('#training-open');page.get_by_role('button',name='얀 선택',exact=True).click();page.click('#start')
    def fixture():
        page.evaluate('''() => {const g=__moba.game,p=g.player;for(const f of ['aiChampion','aiMinion','aiNeutral','aiStructure'])g[f]=()=>{};g.map={bounds:g.bounds,walls:[]};Object.assign(p,{x:40,y:20,qCd:0,rCd:0,lastAttackAt:100,lastDamageAt:100});g.units=[p];g.events=[];g.pending=[];g.projectiles=[];g.minionQueue=[];g.practice.lineStopped=true;const t=g.makeChampion('faust',1,9);Object.assign(t,{x:44,y:20,maxHp:10000,hp:10000,lastAttackAt:100,lastDamageAt:100});window.__target=t;}''')
    def aim(x,y):
        pos=page.evaluate('([x,y])=>{const r=__moba.renderer;r.resize();r.follow(__moba.game,true);const s=r.camera.worldToScreen({x,y}),b=r.canvas.getBoundingClientRect();return {x:s.x+b.left,y:s.y+b.top};}',[x,y]);page.mouse.move(pos['x'],pos['y'])
    def change(key):
        page.select_option('#training-champion',key);page.click('#training-change-champion');fixture()
    fixture();aim(45,20)
    page.mouse.down(button='right');page.mouse.up(button='right')
    page.wait_for_function('__moba.game.player.state.yanBarrage')
    assert page.evaluate('''() => {const g=__moba.game,p=g.player;g.status(p,'stun',1,3,__target);return !g.stat(p,'stun')&&!g.startMotion(p,{x:1,y:0},2,{kind:'knock'});}''')
    page.screenshot(path=str(art/'v19-yan-barrage-defense.png'))
    page.wait_for_function('!__moba.game.player.state.yanBarrage')
    page.evaluate('__moba.game.player.state.ominous=6');page.locator('#arena').focus();page.keyboard.press('Space')
    page.wait_for_function('__moba.game.buff(__moba.game.player,"yanDistorted")')
    assert page.evaluate('__moba.game.player.state.ominous===0')
    change('gregor');aim(45,20);page.mouse.down(button='right');page.mouse.up(button='right')
    page.wait_for_function('__target.motion?.forced')
    page.wait_for_timeout(80);page.screenshot(path=str(art/'v19-gregor-pierce.png'))
    page.wait_for_function('Math.hypot(__target.x-__moba.game.player.x,__target.y-__moba.game.player.y)<1.2')
    page.evaluate('''() => {const g=__moba.game,p=g.player;p.state.mutations=11;g.deal(p,__target,1,{fixed:true});}''')
    page.wait_for_function('__moba.game.buff(__moba.game.player,"mutant")')
    page.screenshot(path=str(art/'v19-gregor-brown-mutation.png'))
    change('gregor')
    page.evaluate('''() => {const g=__moba.game;__target.x=43;g.map.walls=[{x:46,y:18,w:.5,h:4}];}''')
    aim(45,20);page.locator('#arena').focus();page.keyboard.press('Space')
    page.wait_for_function('__moba.game.stat(__target,"stun")>0')
    page.screenshot(path=str(art/'v19-gregor-wall-stun.png'))
    change('ahab');page.evaluate('__target.x=43')
    for i in range(3):
        page.wait_for_function('__moba.game.player.attackCd===0');page.evaluate('__moba.game.player.ammo=3');aim(43,20)
        page.mouse.down();page.mouse.up();page.wait_for_function(f'__moba.game.player.basicHits[__target.id]==={i+1}')
    page.evaluate('''() => {const g=__moba.game,p=g.player,a=g.makeChampion('faust',0,9);Object.assign(a,{x:40,y:22,hp:10000,maxHp:10000});window.__ally=a;g.deal(a,__target,65,{proc:false});}''')
    page.wait_for_function('__moba.game.buff(__moba.game.player,"ahabCover")')
    expect(page.locator('#buff-list')).to_contain_text('엄호해라!')
    page.screenshot(path=str(art/'v19-ahab-cover.png'))
    aim(43,20);page.mouse.down(button='right');page.mouse.up(button='right')
    page.wait_for_function('__moba.game.player.state.order==="guard"')
    expect(page.locator('#buff-list')).to_contain_text('자, 막아내라!')
    assert page.evaluate('''() => {const g=__moba.game,p=g.player,h=p.hp,a=__ally.hp;g.deal(__target,p,100,{fixed:true});return Math.abs(h-p.hp-70)<1e-6&&Math.abs(a-__ally.hp-30)<1e-6;}''')
    page.screenshot(path=str(art/'v19-ahab-guard-link.png'))
    page.click('#pause');page.click('#leave');page.click('#archive-open');page.locator('[data-category=rules]').click()
    expect(page.locator('#codex-content')).to_contain_text('10초당 한 번')
    expect(page.locator('#codex-content')).to_contain_text('12.5%')
    page.locator('[data-category=monsters]').click();expect(page.locator('#codex-content')).to_contain_text('포탑 대상 방어력 +30%')
    page.click('#archive .close-dialog')
    page.set_viewport_size({'width':390,'height':844});page.wait_for_timeout(150)
    assert page.evaluate('document.body.scrollWidth<=innerWidth')
    assert not errors,errors;b.close()
    print(json.dumps({'status':'passed','checks':['Yan six-stack transformation and barrage immunity','Gregor pull animation and brown mutation','wall-only ultimate collision stun','Ahab third hits, proc-free cover and guard transfer','live order and guard link UI','role/defense codex and mobile layout'],'page_errors':errors},ensure_ascii=False))
